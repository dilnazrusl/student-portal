-- ---------- 1. Статусы ----------
ALTER TABLE student ADD COLUMN IF NOT EXISTS status VARCHAR(30) NOT NULL DEFAULT 'Active';
ALTER TABLE student DROP CONSTRAINT IF EXISTS ck_student_status;
