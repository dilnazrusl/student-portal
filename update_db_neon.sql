-- ---------- 2. Сотрудники ----------
CREATE TABLE IF NOT EXISTS staff (
    staff_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       VARCHAR(100) NOT NULL,
    email      VARCHAR(100) NOT NULL UNIQUE,
    department VARCHAR(30)  NOT NULL,
    password   VARCHAR(50)  NOT NULL UNIQUE,
    CONSTRAINT ck_staff_department CHECK (department IN ('HR', 'Registrar', 'IT')),
    CONSTRAINT ck_staff_password CHECK (
    char_length(password) >= 8
    AND password ~ '[[:upper:]]'
    AND password ~ '[[:lower:]]'
    AND password ~ '[[:digit:]]'
    AND password ~ '[!@#$%]'
    )
);

-- ---------- 3. Журналы ----------
CREATE TABLE IF NOT EXISTS login_log (
    log_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role      VARCHAR(20)  NOT NULL CHECK (role IN ('student', 'instructor', 'staff')),
    user_id   INTEGER      NOT NULL,
    user_name VARCHAR(100) NOT NULL,
    logged_at TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_login_log_user ON login_log (role, user_id);

CREATE TABLE IF NOT EXISTS grade_change_log (
    log_id          INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instructor_id   INTEGER      NOT NULL,
    instructor_name VARCHAR(100) NOT NULL,
    student_id      INTEGER      NOT NULL,
    student_name    VARCHAR(100) NOT NULL,
    course_code     VARCHAR(10)  NOT NULL,
    semester        VARCHAR(20)  NOT NULL,
    old_grade       NUMERIC(5, 2),
    new_grade       NUMERIC(5, 2),
    changed_at      TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_grade_log_instructor ON grade_change_log (instructor_id);

CREATE TABLE IF NOT EXISTS staff_action_log (
    log_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_id    INTEGER      NOT NULL,
    staff_name  VARCHAR(100) NOT NULL,
    department  VARCHAR(30)  NOT NULL,
    action      VARCHAR(30)  NOT NULL,
    target_type VARCHAR(20)  NOT NULL,
    target_id   INTEGER,
    target_name VARCHAR(100),
    details     TEXT,
    acted_at    TIMESTAMP    NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_staff_log_staff  ON staff_action_log (staff_id);
CREATE INDEX IF NOT EXISTS idx_staff_log_target ON staff_action_log (target_type, target_id);

