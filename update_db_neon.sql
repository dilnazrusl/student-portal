
-- =========================================================================
-- 1. СОЗДАНИЕ ТАБЛИЦ
-- =========================================================================

-- 1. Студенты
CREATE TABLE student (
    student_id  INTEGER GENERATED BY DEFAULT AS IDENTITY,
    iin         VARCHAR(12)  NOT NULL,
    name        VARCHAR(100) NOT NULL,
    email       VARCHAR(100) NOT NULL
);

-- 2. Преподаватели
CREATE TABLE instructor (
    instructor_id INTEGER GENERATED BY DEFAULT AS IDENTITY,
    name          VARCHAR(100) NOT NULL,
    email         VARCHAR(100) NOT NULL,
    department    VARCHAR(100) NOT NULL
);

-- 3. Курсы
CREATE TABLE course (
    course_code VARCHAR(10)  NOT NULL,
    course_name VARCHAR(120) NOT NULL,
    credits     SMALLINT     NOT NULL
);

-- 4. Экстренный контакт (слабая сущность — частичный ключ contact_name)
CREATE TABLE emergency_contact (
    contact_name VARCHAR(100) NOT NULL,
    phone        VARCHAR(20)  NOT NULL,
    relationship VARCHAR(50)  NOT NULL
);

-- 5. "has" — идентифицирующая связь Student -> EmergencyContact
CREATE TABLE has (
    student_id   INTEGER      NOT NULL,
    contact_name VARCHAR(100) NOT NULL
);

-- 6. "teacher" — связь многие-ко-многим Instructor <-> Course
CREATE TABLE teacher (
    instructor_id INTEGER     NOT NULL,
    course_code   VARCHAR(10) NOT NULL
);

-- 7. Enrollment — связь многие-ко-многим Student <-> Course (с атрибутами)
CREATE TABLE enrollment (
    student_id  INTEGER     NOT NULL,
    course_code VARCHAR(10) NOT NULL,
    semester    VARCHAR(20) NOT NULL,
    grade       NUMERIC(5, 2)
);


